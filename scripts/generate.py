#!/usr/bin/env python3
"""Build mutually exclusive RouterOS IPv4 ISP address lists.

Only local source files are read. This program does not fetch upstream data,
publish artifacts, or contact a router.
"""
from __future__ import annotations

import argparse
import hashlib
import ipaddress
import json
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Iterable

Network = ipaddress.IPv4Network


def read_networks(path: Path) -> tuple[list[Network], int]:
    parsed: list[Network] = []
    raw_count = 0
    errors: list[str] = []
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except OSError as exc:
        raise ValueError(f"cannot read {path}: {exc}") from exc

    for line_no, raw in enumerate(lines, 1):
        value = raw.strip()
        if not value or value.startswith("#"):
            continue
        raw_count += 1
        try:
            item = ipaddress.ip_network(value, strict=False)
            if not isinstance(item, ipaddress.IPv4Network):
                raise ValueError("IPv6 is not accepted")
            parsed.append(item)
        except ValueError as exc:
            errors.append(f"{path}:{line_no}: {value!r}: {exc}")

    if errors:
        preview = "\n".join(errors[:20])
        suffix = f"\n... and {len(errors) - 20} more" if len(errors) > 20 else ""
        raise ValueError(f"invalid source entries ({len(errors)}):\n{preview}{suffix}")
    if not parsed:
        raise ValueError(f"{path}: source is empty")
    return list(ipaddress.collapse_addresses(parsed)), raw_count


def _bounds(networks: Iterable[Network]) -> list[tuple[int, int]]:
    return sorted((int(n.network_address), int(n.broadcast_address)) for n in networks)


def _from_bounds(start: int, end: int) -> list[Network]:
    return list(ipaddress.summarize_address_range(
        ipaddress.IPv4Address(start), ipaddress.IPv4Address(end)
    ))


def subtract_networks(source: Iterable[Network], excluded: Iterable[Network]) -> list[Network]:
    """Return source address space minus excluded address space in O(n log n)."""
    src = _bounds(source)
    exc = _bounds(excluded)
    result: list[Network] = []
    j = 0

    for start, end in src:
        cursor = start
        while j < len(exc) and exc[j][1] < cursor:
            j += 1
        k = j
        while k < len(exc) and exc[k][0] <= end:
            ex_start, ex_end = exc[k]
            if ex_start > cursor:
                result.extend(_from_bounds(cursor, min(end, ex_start - 1)))
            cursor = max(cursor, ex_end + 1)
            if cursor > end:
                break
            k += 1
        if cursor <= end:
            result.extend(_from_bounds(cursor, end))
    return list(ipaddress.collapse_addresses(result))


def overlap_networks(a: Iterable[Network], b: Iterable[Network]) -> list[Network]:
    """Return the intersection of two disjoint, collapsed network sets."""
    left = _bounds(a)
    right = _bounds(b)
    intersections: list[Network] = []
    i = j = 0
    while i < len(left) and j < len(right):
        lo = max(left[i][0], right[j][0])
        hi = min(left[i][1], right[j][1])
        if lo <= hi:
            intersections.extend(_from_bounds(lo, hi))
        if left[i][1] < right[j][1]:
            i += 1
        else:
            j += 1
    return list(ipaddress.collapse_addresses(intersections))


def validate_disjoint(ct_only: list[Network], cmcc_only: list[Network]) -> None:
    ct = _bounds(ct_only)
    cmcc = _bounds(cmcc_only)
    i = j = 0
    while i < len(ct) and j < len(cmcc):
        if ct[i][0] <= cmcc[j][1] and cmcc[j][0] <= ct[i][1]:
            raise ValueError(f"final output overlaps: {ct[i]} and {cmcc[j]}")
        if ct[i][1] < cmcc[j][1]:
            i += 1
        else:
            j += 1


def render_rsc(ct_only: list[Network], cmcc_only: list[Network]) -> str:
    lines = [
        "# Generated by IPList-Generator; do not edit manually.",
        "# Ambiguous CT/CMCC overlap and unclassified space are intentionally omitted.",
        "/ip firewall address-list",
    ]
    for list_name, networks in (("dpbr-CT", ct_only), ("dpbr-CMCC", cmcc_only)):
        for network in sorted(networks, key=lambda n: (int(n.network_address), n.prefixlen)):
            lines.append(f"add list={list_name} address={network.with_prefixlen}")
    return "\n".join(lines) + "\n"


def sha256_text(value: str) -> str:
    return hashlib.sha256(value.encode("utf-8")).hexdigest()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ct-file", required=True, type=Path)
    parser.add_argument("--cmcc-file", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--report", required=True, type=Path)
    args = parser.parse_args()

    try:
        ct, ct_raw = read_networks(args.ct_file)
        cmcc, cmcc_raw = read_networks(args.cmcc_file)
        overlap = overlap_networks(ct, cmcc)
        ct_only = subtract_networks(ct, cmcc)
        cmcc_only = subtract_networks(cmcc, ct)
        validate_disjoint(ct_only, cmcc_only)

        if not ct_only or not cmcc_only:
            raise ValueError("one exclusive output list is empty; refusing to generate")

        rsc = render_rsc(ct_only, cmcc_only)
        for line in rsc.splitlines():
            if line.startswith("#") or line == "/ip firewall address-list":
                continue
            if not (line.startswith("add list=dpbr-CT address=") or
                    line.startswith("add list=dpbr-CMCC address=")):
                raise ValueError(f"unexpected RSC command: {line}")

        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(rsc, encoding="utf-8", newline="\n")
        report = {
            "generated_at_utc": datetime.now(timezone.utc).isoformat(),
            "policy": "CT-only and CMCC-only address space; all overlap omitted",
            "sources": {
                "ct_file": args.ct_file.name,
                "cmcc_file": args.cmcc_file.name,
                "ct_raw_entries": ct_raw,
                "cmcc_raw_entries": cmcc_raw,
                "ct_collapsed_prefixes": len(ct),
                "cmcc_collapsed_prefixes": len(cmcc),
            },
            "results": {
                "overlap_prefixes": len(overlap),
                "overlap_addresses": sum(n.num_addresses for n in overlap),
                "ct_only_prefixes": len(ct_only),
                "ct_only_addresses": sum(n.num_addresses for n in ct_only),
                "cmcc_only_prefixes": len(cmcc_only),
                "cmcc_only_addresses": sum(n.num_addresses for n in cmcc_only),
                "final_lists_disjoint": True,
            },
            "output": {
                "file": args.output.name,
                "bytes": len(rsc.encode("utf-8")),
                "sha256": sha256_text(rsc),
            },
        }
        args.report.write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n",
                               encoding="utf-8")
        print(json.dumps(report, indent=2, ensure_ascii=False))
        return 0
    except (ValueError, OSError, AssertionError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
